/**
 * Publish exactly what a model-driven mind is told.
 *
 *   pnpm gen:prompts           rewrite docs/PROMPTS.md from the code
 *   pnpm gen:prompts --check   fail if the document is out of date
 *
 * The document is generated, never written by hand, so that what is published is what is
 * sent: the rules text for each kind of world, one example page rendered from a fixed
 * world, and the answer schema.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { AFFORDANCE_VERSION, ENGINE_VERSION, createWorld, makeConfig, observe, step, type SimEvent } from "../src/engine";
import { PROMPT_VERSION, buildRequest, inputTokenBound, promptFeatures, systemPrompt } from "../src/providers/prompt";
import { WIRE_VERSION, decisionSchema, lintSchema } from "../src/providers/wire";

const OUT = "docs/PROMPTS.md";

function examplePage(context: "rich" | "minimal"): { page: string; bound: number; system: number } {
  // a fixed, lived-in world: day 4 of First Light, seed 3, agreements allowed
  const cfg = makeConfig("first_light", 3, { externalShare: 1000, institutions: "open" });
  const world = createWorld(cfg);
  const out: SimEvent[] = [];
  for (let i = 0; i < 96 * 3 + 40; i++) {
    step(world, out);
    out.length = 0;
  }
  const agent = world.agents.find((a) => a.alive && !a.asleep && a.mind.inbox.length > 0) ?? world.agents.find((a) => a.alive && !a.asleep)!;
  const req = buildRequest(observe(world, agent.id)!, promptFeatures(cfg), context);
  return { page: req.user, bound: inputTokenBound(req), system: req.system.length };
}

function render(): string {
  const full = systemPrompt({ civic: true, propose: true, escrow: true, planting: true, takeable: true, crafts: false });
  const plain = systemPrompt({ civic: false, propose: false, escrow: false, planting: true, takeable: true, crafts: false });
  const crafted = systemPrompt({ civic: true, propose: true, escrow: true, planting: true, takeable: true, crafts: true });
  const lineOf = (text: string, starts: string): string => text.split("\n").find((l) => l.startsWith(starts)) ?? "";
  const sectionOf = (text: string, head: string): string => text.split("\n\n").find((part) => part.startsWith(head)) ?? "";
  const rich = examplePage("rich");
  const minimal = examplePage("minimal");
  const schema = decisionSchema(true);
  const lint = lintSchema(schema);
  const fence = "```";
  return [
    "# What a model-driven mind is told",
    "",
    `Generated by \`pnpm gen:prompts\` from \`src/providers/prompt.ts\` and \`src/providers/wire.ts\`. Do not edit by hand.`,
    "",
    `- Prompt version **${PROMPT_VERSION}** · answer format version **${WIRE_VERSION}** · engine ${ENGINE_VERSION} · affordances ${AFFORDANCE_VERSION}`,
    "- A request is two texts: the **rules text** (the same for every person and every call in a run) and one person's **page** (rendered from that person's observation and nothing else).",
    "- A change to any wording here is a new prompt version. Recorded runs keep the version they were made with.",
    "- Nothing here has been sent to a model by this project: no live call has been made (see `docs/EVIDENCE.md`).",
    "",
    "What is deliberately absent, and tested for (`src/providers/prompt.test.ts`): any name of a ready-made institution (government, money, market, law, council, tax …), any example of an agreement, and any advice about how to live. A world without the agreement affordance is told nothing about agreements at all.",
    "",
    "## Rules text — a world where people may write agreements",
    "",
    `${full.length.toLocaleString("en-US")} characters.`,
    "",
    `${fence}text`,
    full,
    fence,
    "",
    "## Rules text — a world with no agreement affordance",
    "",
    `${plain.length.toLocaleString("en-US")} characters.`,
    "",
    `${fence}text`,
    plain,
    fence,
    "",
    "## What a world with crafts adds (prompt p3)",
    "",
    "A world whose `crafts` switch is on tells its minds three more things, and nothing else changes: the structures list names the six works, a section says how a craft is come by, and the page says which crafts the person knows. A world without crafts is told none of it — its rules text is, word for word, the two above, which are what prompt p2 was. No age, legacy or aim is mentioned to anyone: those are the observer's.",
    "",
    "The structures line becomes:",
    "",
    `${fence}text`,
    lineOf(crafted, "Structures (build"),
    fence,
    "",
    "The added section:",
    "",
    `${fence}text`,
    sectionOf(crafted, "CRAFTS"),
    fence,
    "",
    "The line of the answer format that changes:",
    "",
    `${fence}text`,
    lineOf(crafted, "  refuel target"),
    fence,
    "",
    "And on the page, after what the person carries, one of: `Crafts you know: tillage, masonry.` · `You know no craft yet.`",
    "",
    "## An example page (rich context)",
    "",
    "First Light, seed 3, day 4, one waking person. Everything on it comes from that person's own observation: their body, what they carry, who and what is in sight, what they believe about places and how they came to believe it, what they remember, what they have heard.",
    "",
    `${fence}text`,
    rich.page,
    fence,
    "",
    "## The same person's page (minimal context)",
    "",
    "The minimal context leaves out temperament, skills, the person's own record of others and their memories. It is a separate treatment, recorded with every run.",
    "",
    `${fence}text`,
    minimal.page,
    fence,
    "",
    "## The answer schema",
    "",
    "Sent as `output_config.format` (`type: json_schema`). Checked offline against the documented limits of structured outputs: " + (lint.length === 0 ? "no violations found." : `VIOLATIONS: ${lint.join("; ")}`) + " Whether the provider's grammar compiler accepts it has not been tested (it needs a live call).",
    "",
    `${fence}json`,
    JSON.stringify(schema, null, 2),
    fence,
    "",
    "## Size of a request",
    "",
    `For the example above: rules text ${rich.system.toLocaleString("en-US")} characters, page ${rich.page.length.toLocaleString("en-US")} characters, schema ${JSON.stringify(schema).length.toLocaleString("en-US")} characters. The ledger's upper bound on its input is **${rich.bound.toLocaleString("en-US")} tokens** — the byte length of all three, because a token is never shorter than a byte. That is a bound, not a count: the real number of tokens is unknown until a call is made or counted, and is expected to be several times smaller.`,
    "",
  ].join("\n");
}

const text = render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // missing counts as out of date
  }
  if (current !== text) {
    console.error(`${OUT} is out of date. Run: pnpm gen:prompts`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT} (${text.length} bytes).`);
}
