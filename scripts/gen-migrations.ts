/**
 * Embed the SQL migrations in a TypeScript module, so that the server needs no filesystem
 * access at run time (and a serverless bundle does not have to carry the project tree).
 *
 *   pnpm gen:migrations           rewrite src/server/migrations.generated.ts from db/migrations
 *   pnpm gen:migrations --check   fail if the generated module is out of date
 *
 * db/migrations/*.sql is the source of truth. Never edit a migration that has been applied
 * anywhere: add a new numbered file.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = join("db", "migrations");
const OUT = join("src", "server", "migrations.generated.ts");

function render(): string {
  const files = readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort();
  const entries = files.map((f) => `  { version: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(DIR, f), "utf8"))} },`);
  return [
    "// GENERATED by scripts/gen-migrations.ts from db/migrations/*.sql — do not edit by hand.",
    "// Run `pnpm gen:migrations` after adding a migration.",
    'import "server-only";',
    "",
    "export interface Migration {",
    "  version: string;",
    "  sql: string;",
    "}",
    "",
    "export const MIGRATIONS: readonly Migration[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

const text = render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // missing counts as out of date
  }
  if (current !== text) {
    console.error(`${OUT} is out of date. Run: pnpm gen:migrations`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT} (${text.length} bytes).`);
}
